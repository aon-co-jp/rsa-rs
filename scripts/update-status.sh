#!/bin/bash
# 軽量: 上流 rsa / crypto-bigint の最新版と RUSTSEC-2023-0071 の状況を取得し、
# STATUS.md (英日) と status.json を再生成する。ビルドや試験は走らせない (VPS でも安全)。
# 試験結果は tests-result.txt (nightly.sh が作る: PASS/FAIL と時刻) があれば反映する。
# 差分があれば終了コード 10 (変化あり) を返す。
set -u
cd "$(dirname "$0")/.."
UA="rsa-rs-status/0.1 (+https://github.com/aon-co-jp/rsa-rs)"
get() { curl -fsS --max-time 20 -A "$UA" "$1" 2>/dev/null; }

latest() { # crates.io の max_stable_version / max_version
  get "https://crates.io/api/v1/crates/$1" | tr ',' '\n' | grep -m1 "\"$2\"" | sed 's/.*:"\([^"]*\)".*/\1/'
}
RSA_STABLE=$(latest rsa max_stable_version); RSA_MAX=$(latest rsa max_version)
BIGINT=$(latest crypto-bigint max_stable_version)
ADV=$(get "https://raw.githubusercontent.com/RustSec/advisory-db/main/crates/rsa/RUSTSEC-2023-0071.md")
if [ -z "$ADV" ]; then PATCHED="unknown (fetch failed)"; else
  PATCHED=$(printf '%s\n' "$ADV" | grep -m1 '^patched' | sed 's/^patched *= *//')
  [ -z "$PATCHED" ] && PATCHED='[]'
fi
: "${RSA_STABLE:=unknown}"; : "${RSA_MAX:=unknown}"; : "${BIGINT:=unknown}"
TESTS="not run"; TESTS_AT=""
if [ -f tests-result.txt ]; then TESTS=$(head -1 tests-result.txt); TESTS_AT=$(sed -n 2p tests-result.txt); fi
DATE=$(date -u +%Y-%m-%d)
COMMIT=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)

NEW=$(mktemp)
cat > "$NEW" <<EOF
{
  "checked": "$DATE",
  "rsa_rs_commit": "$COMMIT",
  "upstream_rsa_max_stable": "$RSA_STABLE",
  "upstream_rsa_max": "$RSA_MAX",
  "rustsec_2023_0071_patched": "$PATCHED",
  "crypto_bigint_latest_stable": "$BIGINT",
  "crypto_bigint_required": ">=0.7.10",
  "tests": "$TESTS",
  "tests_at": "$TESTS_AT",
  "audited": false,
  "notice": "Experimental, NOT audited by any third party. / 実験的・第三者監査なし。"
}
EOF
CHANGED=0
# 日付と commit 以外が変わったか
strip() { grep -v '"checked"\|"rsa_rs_commit"\|"tests_at"' "$1" 2>/dev/null; }
if ! diff -q <(strip status.json) <(strip "$NEW") >/dev/null 2>&1; then CHANGED=1; fi
mv "$NEW" status.json

cat > STATUS.md <<EOF
# STATUS / 状況

> **EN:** Experimental. **Not audited by any third party.** Constant-time behaviour has only been sampled, not proven. Auto-generated by \`scripts/update-status.sh\` — do not edit.
> **JA:** 実験的。**第三者監査なし。** 定数時間性は簡易計測のみで証明ではありません。\`scripts/update-status.sh\` が自動生成します(手で編集しない)。

| Item / 項目 | Value / 値 |
|---|---|
| Checked (UTC) / 確認日 | $DATE |
| rsa-rs commit | $COMMIT |
| Upstream \`rsa\` latest stable / 上流 rsa 最新安定版 | $RSA_STABLE |
| Upstream \`rsa\` latest (incl. pre-release) / 最新(プレリリース含む) | $RSA_MAX |
| RUSTSEC-2023-0071 patched versions / 修正版 | $PATCHED |
| \`crypto-bigint\` latest stable / 最新安定版 | $BIGINT (required / 要求: >=0.7.10) |
| Test result / 試験結果 | $TESTS ($TESTS_AT) |

Machine-readable: [\`status.json\`](status.json). Details / 詳細: [README](README.md), [docs/RESEARCH.md](docs/RESEARCH.md).

If "patched versions" becomes non-empty, upstream \`rsa\` may have a fix — re-evaluate whether this replacement is still needed.
修正版が空でなくなったら、上流に修正がある可能性があります。この置き換えが引き続き必要か再評価してください。
EOF
echo "status updated (changed=$CHANGED): rsa=$RSA_STABLE/$RSA_MAX patched=$PATCHED bigint=$BIGINT tests=$TESTS"
[ "$CHANGED" = 1 ] && exit 10 || exit 0
